"""Vendors the body/muscle SVG paths from react-muscle-highlighter (MIT) into ABOT.

    npm pack react-muscle-highlighter@1.2.0 && tar xzf react-muscle-highlighter-1.2.0.tgz
    python3 scripts/vendor-muscle-paths.py package

Reads the package's JS files as plain text (nothing is executed) and writes
src/components/anatomy/bodyPaths.generated.ts. Only path data is taken, not the component.
"""
import json, os, re, sys

pkg = sys.argv[1]
assets = os.path.join(pkg, "dist/esm/assets")
wrapper = open(os.path.join(pkg, "dist/esm/components/SvgMaleWrapper.js"), encoding="utf-8").read()
license_text = open(os.path.join(pkg, "LICENSE"), encoding="utf-8").read().strip()
version = json.load(open(os.path.join(pkg, "package.json")))["version"]

def parts(name):
    src = open(os.path.join(assets, name), encoding="utf-8").read()
    out = []
    for block in re.split(r'\n\s*\{\s*\n\s*slug:', src)[1:]:
        slug = re.match(r'\s*"([a-z-]+)"', block).group(1)
        body = block.split("\n    },")[0]
        out.append({"slug": slug, "d": re.findall(r'"(M[^"]+)"', body)})
    return out

outline = {side: d for d, side in re.findall(r'd: "(M [^"]+)", "aria-label": "male-body-outline-(front|back)"', wrapper)}
front, back = parts("bodyFront.js"), parts("bodyBack.js")
if not front or not back or set(outline) != {"front", "back"}:
    sys.exit("unexpected package layout; nothing written")

comment = "\n".join(" * " + line if line else " *" for line in license_text.splitlines())
ts = f"""/**
 * Generated by scripts/vendor-muscle-paths.py from react-muscle-highlighter {version}
 * (https://github.com/soroojshehryar/react-muscle-highlighter). Do not edit by hand.
 * Front paths use x 0..724, back paths x 724..1448, both y 0..1448.
 *
{comment}
 */
export interface BodyPart {{
  slug: string;
  d: string[];
}}

export const BODY_FRONT: BodyPart[] = {json.dumps(front)};

export const BODY_BACK: BodyPart[] = {json.dumps(back)};

export const OUTLINE_FRONT = {json.dumps(outline["front"])};

export const OUTLINE_BACK = {json.dumps(outline["back"])};
"""
dst = os.path.join(os.path.dirname(__file__), "..", "src/components/anatomy/bodyPaths.generated.ts")
open(dst, "w", encoding="utf-8").write(ts)
print(f"wrote {len(front)} front and {len(back)} back parts to {os.path.normpath(dst)}")
