// Needs the network proxy for Node: NODE_USE_ENV_PROXY=1 when behind one.
// Downloads the food photos listed in scripts/food-photos.json (Pexels / Unsplash, both free
// for commercial use, credit optional), crops each to a 320 px square WebP in public/food/, and
// writes src/data/food-photos.generated.ts with the credits. Run once after editing the list:
//
//   node scripts/fetch-food-photos.mjs
//
// The app never fetches these at runtime: the files ship with it and work offline.
import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";

const root = path.resolve(import.meta.dirname, "..");
const list = JSON.parse(fs.readFileSync(path.join(root, "scripts/food-photos.json"), "utf8"));
const out = path.join(root, "public/food");
fs.mkdirSync(out, { recursive: true });

const credits = {};
let bytes = 0;
for (const p of list) {
  if (!/^https:\/\/images\.(pexels|unsplash)\.com\//.test(p.url)) throw new Error(`Not a Pexels or Unsplash image: ${p.id}`);
  const res = await fetch(p.url);
  if (!res.ok) throw new Error(`${p.id}: HTTP ${res.status}`);
  const buf = Buffer.from(await res.arrayBuffer());
  const webp = await sharp(buf).resize(320, 320, { fit: "cover", position: "attention" }).webp({ quality: 72 }).toBuffer();
  fs.writeFileSync(path.join(out, `${p.id}.webp`), webp);
  bytes += webp.length;
  credits[p.id] = { author: p.author ?? null, site: p.site, page: p.page };
  process.stdout.write(".");
}

const ts = `// Generated by scripts/fetch-food-photos.mjs: one bundled photo per food (public/food/<id>.webp),
// with its photographer and source. Do not edit by hand.
export interface FoodPhotoCredit {
  author: string | null;
  site: "Unsplash" | "Pexels";
  page: string;
}

export const FOOD_PHOTOS: Record<string, FoodPhotoCredit> = ${JSON.stringify(credits, null, 2)};
`;
fs.writeFileSync(path.join(root, "src/data/food-photos.generated.ts"), ts);
console.log(`\n${list.length} photos, ${(bytes / 1024).toFixed(0)} KB in public/food`);
