// Builds the main extended exercise library from free-exercise-db
// (https://github.com/yuhonas/free-exercise-db, public domain, Unlicense): about 780 exercises
// beyond the seed library, each with its start and end photos, the same look as the seed list.
//
//   node scripts/build-fedb-library.mjs           fetch, trim, write (keeps thumbnails already made)
//   node scripts/build-fedb-library.mjs --force   make every thumbnail again
//
// Writes src/data/fedb-library.generated.ts (rows as the dataset has them; the app maps them with
// data/catalog.ts mapCatalogEntry) and a 128 px thumbnail per exercise in public/thumbs/fedb/, so
// lists show photos offline (about 2.5 MB). The two full photos load from the pinned commit on
// the detail page when online. Run scripts/build-atlas-catalog.mjs after this one: it keeps only
// the Atlas exercises this library does not have. Needs NODE_USE_ENV_PROXY=1 behind a proxy.
import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";

/** The free-exercise-db commit the library is built from; bump it to take in changes. */
const COMMIT = "f00c92c7dcf1216a928a52c3706c7ce8e2f71ed5";
// The app builds photo URLs from src/data/fedb-commit.ts; both must name the same commit.
if (!fs.readFileSync(new URL("../src/data/fedb-commit.ts", import.meta.url), "utf8").includes(COMMIT)) throw new Error("src/data/fedb-commit.ts names another commit");
const RAW = `https://raw.githubusercontent.com/yuhonas/free-exercise-db/${COMMIT}/`;

const root = path.resolve(import.meta.dirname, "..");
const thumbDir = path.join(root, "public/thumbs/fedb");
fs.mkdirSync(thumbDir, { recursive: true });
const force = process.argv.includes("--force");

async function get(url) {
  const res = await fetch(url, { headers: { "User-Agent": "ABOT-library-build/1.0" } });
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  return res;
}

const seedText = fs.readFileSync(path.join(root, "src/data/seed-exercises.generated.ts"), "utf8");
const seed = JSON.parse(seedText.slice(seedText.indexOf("= [") + 2, seedText.lastIndexOf("]") + 1));
const seedSources = new Set(seed.map((s) => s.sourceId).filter(Boolean));

const data = await (await get(`${RAW}dist/exercises.json`)).json();
const rows = [];
let made = 0;
for (const d of data) {
  if (typeof d.id !== "string" || !/^[A-Za-z0-9_-]+$/.test(d.id) || seedSources.has(d.id)) continue;
  const images = (d.images ?? []).filter((i) => typeof i === "string" && /^[A-Za-z0-9_-]+\/\d\.jpg$/.test(i)).slice(0, 2);
  if (images[0]) {
    const file = path.join(thumbDir, `${d.id}.webp`);
    if (force || !fs.existsSync(file)) {
      const buf = Buffer.from(await (await get(RAW + "exercises/" + images[0])).arrayBuffer());
      fs.writeFileSync(file, await sharp(buf).resize(128, 128, { fit: "cover" }).webp({ quality: 65, effort: 6 }).toBuffer());
      made++;
      if (made % 50 === 0) process.stdout.write(".");
    }
  }
  rows.push({
    id: d.id,
    name: d.name,
    equipment: d.equipment ?? null,
    category: d.category ?? null,
    mechanic: d.mechanic ?? null,
    primaryMuscles: d.primaryMuscles ?? [],
    secondaryMuscles: d.secondaryMuscles ?? [],
    instructions: d.instructions ?? [],
    images,
  });
}

const ts = `// Generated by scripts/build-fedb-library.mjs from free-exercise-db at ${COMMIT.slice(0, 7)}
// (public domain, Unlicense). Do not edit by hand: change the script and run it again.

/** Dataset rows minus the seed library's; data/catalog.ts mapCatalogEntry turns them into exercises. */
export const FEDB_ROWS: unknown[] = ${JSON.stringify(rows)};
`;
fs.writeFileSync(path.join(root, "src/data/fedb-library.generated.ts"), ts);
console.log(`\n${rows.length} exercises, ${made} new thumbnails`);
