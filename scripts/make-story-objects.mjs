#!/usr/bin/env node
// Writes src/lib/story-objects.generated.ts: the Solar (CC BY 4.0) shapes the Clean story draws
// for "like lifting 2 cars", as canvas paths. Rerun after changing OBJECTS below.
import fs from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const solar = require("@iconify-json/solar/icons.json");
const OBJECTS = { cat: "cat-bold", bicycle: "bicycle-bold", fridge: "fridge-bold", car: "car-bold", bus: "bus-bold", airplane: "airplane-bold" };

const out = {};
for (const [id, name] of Object.entries(OBJECTS)) {
  const body = solar.icons[name].body;
  const groupEvenOdd = /<g[^>]*fill-rule="evenodd"/.test(body);
  const paths = [];
  for (const m of body.matchAll(/<path([^>]*)\/?>/g)) {
    const attrs = m[1];
    const d = /\sd="([^"]+)"/.exec(attrs)?.[1];
    if (!d) continue;
    const opacity = Number(/opacity="([\d.]+)"/.exec(attrs)?.[1] ?? 1);
    paths.push({ d, evenOdd: groupEvenOdd || /fill-rule="evenodd"/.test(attrs), opacity });
  }
  out[id] = paths;
}

const file = `// Generated by scripts/make-story-objects.mjs from @iconify-json/solar (CC BY 4.0). Do not edit.
export type StoryObjectPath = { d: string; evenOdd: boolean; opacity: number };
export const STORY_OBJECT_PATHS: Record<string, StoryObjectPath[]> = ${JSON.stringify(out, null, 2)};
`;
fs.writeFileSync(new URL("../src/lib/story-objects.generated.ts", import.meta.url), file);
console.log(`${Object.keys(out).length} objects written`);
