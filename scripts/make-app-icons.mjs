#!/usr/bin/env node
/**
 * Draws ABOT's icons from the one mark path (src/components/brand/mark-path.ts): the favicon
 * (src/app/icon.svg), Android's status-bar icon (drawable/ic_stat_abot.xml) and the launcher
 * PNGs (adaptive foreground, square and round legacy icons, every density). Run it after
 * changing the mark:  node scripts/make-app-icons.mjs
 * Uses the preinstalled Playwright Chromium to rasterise.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { join } from "node:path";

const ROOT = join(import.meta.dirname, "..");
const RES = join(ROOT, "android/app/src/main/res");
const VOLT = "#ccff00";
const OBSIDIAN = "#09090b";

// The mark is the four path constants joined; read them from the source so there is one truth.
const src = readFileSync(join(ROOT, "src/components/brand/mark-path.ts"), "utf8");
const part = (name) => {
  const m = new RegExp(`export const ${name} =\\s*"([^"]+)"`).exec(src);
  if (!m) throw new Error(`${name} not found in mark-path.ts`);
  return m[1];
};
const MARK = ["MARK_A", "MARK_BAR", "MARK_PLATE_LEFT", "MARK_PLATE_RIGHT"].map(part).join(" ");

/** The mark at `scale` of a 100 box, centred, in `color`. */
const markAt = (scale, color) =>
  `<g transform="translate(${50 - 50 * scale} ${50 - 50 * scale}) scale(${scale})"><path d="${MARK}" fill="${color}"/></g>`;

// Favicon: Obsidian tile, Volt mark.
writeFileSync(
  join(ROOT, "src/app/icon.svg"),
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100"><rect width="100" height="100" rx="22" fill="${OBSIDIAN}"/>${markAt(0.72, VOLT)}</svg>\n`,
);

// Status-bar icon: one colour (Android tints it), with a little air around the mark.
writeFileSync(
  join(RES, "drawable/ic_stat_abot.xml"),
  `<?xml version="1.0" encoding="utf-8"?>
<!-- Status bar icon: the ABOT mark (an A with a loaded barbell), single colour (Android tints it).
     Generated by scripts/make-app-icons.mjs from src/components/brand/mark-path.ts. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="112"
    android:viewportHeight="112">
    <group android:translateX="6" android:translateY="6">
        <path
            android:fillColor="#FFFFFFFF"
            android:pathData="${MARK}" />
    </group>
</vector>
`,
);

const DENSITIES = { mdpi: 1, hdpi: 1.5, xhdpi: 2, xxhdpi: 3, xxxhdpi: 4 };
const icons = [];
for (const [d, k] of Object.entries(DENSITIES)) {
  // Adaptive foreground: 108 dp canvas, launcher masks to the middle 66 dp, so the mark sits in ~54 dp.
  icons.push({ file: `mipmap-${d}/ic_launcher_foreground.png`, px: 108 * k, svg: markAt(0.5, VOLT) });
  // Legacy icons (Android 7 and older): the whole tile is drawn here.
  icons.push({ file: `mipmap-${d}/ic_launcher.png`, px: 48 * k, svg: `<rect width="100" height="100" rx="22" fill="${OBSIDIAN}"/>${markAt(0.7, VOLT)}` });
  icons.push({ file: `mipmap-${d}/ic_launcher_round.png`, px: 48 * k, svg: `<circle cx="50" cy="50" r="50" fill="${OBSIDIAN}"/>${markAt(0.62, VOLT)}` });
}

const require = createRequire(import.meta.url);
const { chromium } = require("playwright");
const browser = await chromium.launch();
const page = await browser.newPage();
for (const { file, px, svg } of icons) {
  await page.setViewportSize({ width: px, height: px });
  await page.setContent(
    `<html><body style="margin:0;background:transparent"><svg xmlns="http://www.w3.org/2000/svg" width="${px}" height="${px}" viewBox="0 0 100 100">${svg}</svg></body></html>`,
  );
  await page.screenshot({ path: join(RES, file), omitBackground: true });
}
await browser.close();
console.log(`wrote icon.svg, ic_stat_abot.xml and ${icons.length} launcher PNGs`);
