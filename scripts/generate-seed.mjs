#!/usr/bin/env node
// Builds src/data/seed-exercises.generated.ts from scripts/seed-map.json plus free-exercise-db.
//
//   node scripts/generate-seed.mjs [path/to/exercises.json]
//
// Without a path it downloads the dataset (public domain, Unlicense) from GitHub. Instructions
// come from the dataset unless the map supplies its own; form cues are always from the map.
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { cleanSteps } from "../src/data/cleanSteps.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const DATA_URL = "https://raw.githubusercontent.com/yuhonas/free-exercise-db/main/dist/exercises.json";
const IMAGE_BASE = "https://raw.githubusercontent.com/yuhonas/free-exercise-db/main/exercises/";

const map = JSON.parse(await readFile(path.join(root, "scripts/seed-map.json"), "utf8"));
const datasetPath = process.argv[2];
const dataset = datasetPath
  ? JSON.parse(await readFile(datasetPath, "utf8"))
  : await (await fetch(DATA_URL)).json();
const byId = new Map(dataset.map((x) => [x.id, x]));


const out = [];
const problems = [];
for (const row of map) {
  const src = byId.get(row.sourceId);
  if (!src) {
    problems.push(`${row.id}: sourceId ${row.sourceId} not in dataset`);
    continue;
  }
  if (src.images.length < 2) problems.push(`${row.id}: dataset has ${src.images.length} images`);
  const instructions = cleanSteps(row.instructions ?? src.instructions);
  if (instructions.length < 3) problems.push(`${row.id}: only ${instructions.length} instruction steps`);
  if ((row.cues ?? []).length < 2) problems.push(`${row.id}: fewer than 2 form cues`);
  out.push({
    id: row.id,
    name: row.name,
    sourceId: row.sourceId,
    equipment: row.equipment,
    primaryMuscles: row.primary,
    secondaryMuscles: row.secondary,
    ...(row.isBodyweight ? { isBodyweight: true } : {}),
    category: src.mechanic === "isolation" ? "isolation" : "compound",
    instructions,
    formCues: row.cues,
    media: { motionUrls: [0, 1].map((i) => `${IMAGE_BASE}${row.sourceId}/${i}.jpg`) },
  });
}
if (problems.length) {
  console.error(problems.join("\n"));
  process.exit(1);
}

const body = `// Generated by scripts/generate-seed.mjs from scripts/seed-map.json and free-exercise-db
// (https://github.com/yuhonas/free-exercise-db, public domain). Do not edit by hand: edit the
// map and run \`node scripts/generate-seed.mjs\`.
import type { ExerciseInput } from "./normalize";

export const SEED_INPUTS: ExerciseInput[] = ${JSON.stringify(out, null, 2)};
`;
await writeFile(path.join(root, "src/data/seed-exercises.generated.ts"), body);
console.log(`wrote ${out.length} exercises`);
