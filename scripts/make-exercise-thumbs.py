#!/usr/bin/env python3
"""
Builds the exercise list thumbnails that ship with the app, so the library shows a photo of
every seed exercise with no network at runtime.

For each seed exercise it downloads the first frame from free-exercise-db (public domain,
Unlicense), crops it to a square on the centre, scales it to 128 px and saves
public/thumbs/<id>.webp. It also writes src/data/exercise-thumbs.generated.ts, the list of ids
that have a thumbnail. Needs Python 3 with Pillow. Run from the repo root:

    python3 scripts/make-exercise-thumbs.py
"""
import io
import json
import pathlib
import re
import urllib.request

from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent
SEED = ROOT / "src/data/seed-exercises.generated.ts"
OUT = ROOT / "public/thumbs"
LIST = ROOT / "src/data/exercise-thumbs.generated.ts"
SIZE = 128

text = SEED.read_text()
seed = json.loads(text[text.index("= [") + 2 : text.rindex("]") + 1])
OUT.mkdir(parents=True, exist_ok=True)

made = []
for ex in seed:
    urls = ex.get("media", {}).get("motionUrls") or []
    if not urls or not re.match(r"^[a-z0-9-]+$", ex["id"]):
        continue
    with urllib.request.urlopen(urls[0], timeout=30) as r:
        img = Image.open(io.BytesIO(r.read())).convert("RGB")
    side = min(img.size)
    left = (img.width - side) // 2
    top = (img.height - side) // 2
    img = img.crop((left, top, left + side, top + side)).resize((SIZE, SIZE), Image.LANCZOS)
    img.save(OUT / f"{ex['id']}.webp", "WEBP", quality=72, method=6)
    made.append(ex["id"])
    print(ex["id"])

LIST.write_text(
    "// Generated by scripts/make-exercise-thumbs.py. Do not edit by hand.\n"
    "/** Seed exercises with a bundled 128 px thumbnail at /thumbs/<id>.webp. */\n"
    f"export const BUNDLED_THUMBS: ReadonlySet<string> = new Set({json.dumps(sorted(made), indent=2)});\n"
)
print(f"{len(made)} thumbnails")
